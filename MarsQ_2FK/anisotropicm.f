C     Passive, bounded snapshots of the five actual radial grids.
C     Orbit actions are retained until the solved field is available;
C     no energy arrays or dense Hermitian matrices are retained here.
      MODULE KENERGYSNAPSHOTM
      USE, INTRINSIC :: ISO_FORTRAN_ENV, ONLY: DP=>REAL64
      IMPLICIT NONE
      PRIVATE
      PUBLIC :: KESNAP_ACTIVE,KESNAP_ENERGY,KESNAP_ORBIT,KESNAP_USE
      INTEGER, PARAMETER :: MAX_FILES=16,MAX_BYTES=9999999
      INTEGER, PARAMETER :: MAX_TOTAL=59999999,MAX_ORBITS=8002
      TYPE SNAP_ORBIT_T
         INTEGER :: PART=0,L=0,ICASE=0
         REAL(DP) :: META(8)=0.
         COMPLEX(DP) :: W=0.
         COMPLEX(DP), ALLOCATABLE :: V(:,:)
      END TYPE SNAP_ORBIT_T
      TYPE(SNAP_ORBIT_T), ALLOCATABLE, SAVE :: ORBITS(:,:)
      INTEGER, SAVE :: COUNTS(5)=0,REFERENCES(5,5)=0
      LOGICAL, SAVE :: CHECKED=.FALSE.,ENABLED=.FALSE.
      INTEGER, SAVE :: NFILES=0,UNITS(MAX_FILES)=0
      INTEGER, SAVE :: NBYTES(MAX_FILES)=0,TOTAL_BYTES=0
      CHARACTER(96), SAVE :: NAMES(MAX_FILES)=''
      CONTAINS

      INTEGER FUNCTION KESNAP_POOL(JS,KGRID) RESULT(POOL)
      INTEGER, INTENT(IN) :: JS,KGRID
      POOL=0
      IF (KGRID.EQ.1.AND.JS.GE.38.AND.JS.LE.40) POOL=JS-37
      IF (KGRID.EQ.2.AND.JS.GE.38.AND.JS.LE.39) POOL=JS-34
      END FUNCTION KESNAP_POOL

      LOGICAL FUNCTION KESNAP_ACTIVE(JS,KGRID)
      INTEGER, INTENT(IN) :: JS,KGRID
C$OMP CRITICAL(KESNAP_IO)
      IF (.NOT.CHECKED) THEN
         INQUIRE(FILE='ENERGY_SNAPSHOT.REQUEST',EXIST=ENABLED)
         CHECKED=.TRUE.
      ENDIF
C$OMP END CRITICAL(KESNAP_IO)
      KESNAP_ACTIVE=ENABLED.AND.KESNAP_POOL(JS,KGRID).GT.0
      END FUNCTION KESNAP_ACTIVE

      SUBROUTINE KESNAP_LINE(NAME,HEADER,LINE)
      CHARACTER(*), INTENT(IN) :: NAME,HEADER,LINE
      INTEGER :: I,J,IOS,N
C$OMP CRITICAL(KESNAP_IO)
      I=0
      DO J=1,NFILES
         IF (NAMES(J).EQ.NAME) I=J
      ENDDO
      IF (I.EQ.0) THEN
         IF (NFILES.EQ.MAX_FILES) ERROR STOP 'ENERGY SNAPSHOT FILE LIMIT'
         NFILES=NFILES+1
         I=NFILES
         NAMES(I)=NAME
         N=LEN_TRIM(HEADER)+1
         IF (N.GT.MAX_BYTES.OR.TOTAL_BYTES+N.GT.MAX_TOTAL)
     &      ERROR STOP 'ENERGY SNAPSHOT HEADER BYTE LIMIT'
         OPEN(NEWUNIT=UNITS(I),FILE=NAME,STATUS='REPLACE',
     &        ACTION='WRITE',FORM='FORMATTED',IOSTAT=IOS)
         IF (IOS.NE.0) ERROR STOP 'ENERGY SNAPSHOT OPEN FAILED'
         WRITE(UNITS(I),'(A)',IOSTAT=IOS) HEADER
         IF (IOS.NE.0) ERROR STOP 'ENERGY SNAPSHOT HEADER FAILED'
         NBYTES(I)=LEN_TRIM(HEADER)+1
         TOTAL_BYTES=TOTAL_BYTES+NBYTES(I)
      ENDIF
      N=LEN_TRIM(LINE)+1
      IF (NBYTES(I)+N.GT.MAX_BYTES.OR.TOTAL_BYTES+N.GT.MAX_TOTAL)
     &   ERROR STOP 'ENERGY SNAPSHOT BYTE LIMIT'
      WRITE(UNITS(I),'(A)',IOSTAT=IOS) TRIM(LINE)
      IF (IOS.NE.0) ERROR STOP 'ENERGY SNAPSHOT WRITE FAILED'
      NBYTES(I)=NBYTES(I)+N
      TOTAL_BYTES=TOTAL_BYTES+N
      FLUSH(UNITS(I),IOSTAT=IOS)
      IF (IOS.NE.0) ERROR STOP 'ENERGY SNAPSHOT FLUSH FAILED'
C$OMP END CRITICAL(KESNAP_IO)
      END SUBROUTINE KESNAP_LINE

      SUBROUTINE KESNAP_ENERGY(JS,KGRID,PART,L,TAG,NEPK,RL,LAMB,
     &   WEIGHT,ZW,PI,RTMP1,B,C,NU,CPSI,H2,H6,A,BASE,OFFSET,TOTAL)
      INTEGER, INTENT(IN) :: JS,KGRID,PART,L,TAG,NEPK
      REAL(DP), INTENT(IN) :: RL,LAMB,WEIGHT,ZW,PI,RTMP1,
     &                       B,C,NU,CPSI,H2,H6
      COMPLEX(DP), INTENT(IN) :: A,BASE,OFFSET,TOTAL
      CHARACTER(96) :: NAME
      CHARACTER(2048) :: LINE
      WRITE(NAME,'(A,I0,A,I0,A)')
     &   'ENERGY_SNAPSHOT_E',JS,'_G',KGRID,'.OUT'
      WRITE(LINE,'(6(I0,1X),20(ES25.16E3,1X))')
     &   JS,KGRID,PART,L,TAG,NEPK,RL,LAMB,WEIGHT,ZW,PI,RTMP1,
     &   B,C,NU,CPSI,H2,H6,A,BASE,OFFSET,TOTAL
      CALL KESNAP_LINE(NAME,
     & '# V2 JS GRID PART L TAG NEPK RL LAMB WEIGHT ZW PI RTMP1 '//
     & 'B C NU CPSI H2 H6 A_RE A_IM BASE_RE BASE_IM OFFSET_RE '//
     & 'OFFSET_IM TOTAL_RE TOTAL_IM',LINE)
      END SUBROUTINE KESNAP_ENERGY

      SUBROUTINE KESNAP_ORBIT(JS,KGRID,PART,L,ICASE,N,LAMB,LAMH,
     &   WFUN,H4,FAC,OB,OB0,SLAMD0,W,V1,V2,V3,V4,V5)
      INTEGER, INTENT(IN) :: JS,KGRID,PART,L,ICASE,N
      REAL(DP), INTENT(IN) :: LAMB,LAMH,WFUN,H4,FAC,OB,OB0,SLAMD0
      COMPLEX(DP), INTENT(IN) :: W,V1(N),V2(N),V3(N),V4(N),V5(N)
      INTEGER :: POOL,J
      POOL=KESNAP_POOL(JS,KGRID)
      IF (POOL.EQ.0) ERROR STOP 'ENERGY SNAPSHOT GRID LIMIT'
      IF (N.GT.41.OR.L.LT.1.OR.L.GT.5)
     &   ERROR STOP 'ENERGY SNAPSHOT MODE LIMIT'
C$OMP CRITICAL(KESNAP_IO)
      IF (.NOT.ALLOCATED(ORBITS)) ALLOCATE(ORBITS(MAX_ORBITS,5))
C$OMP END CRITICAL(KESNAP_IO)
C     One KJPCOEFF worker owns each distinct (JS,GRID) pool.
      J=COUNTS(POOL)+1
      IF (J.GT.MAX_ORBITS) ERROR STOP 'ENERGY SNAPSHOT ORBIT LIMIT'
      COUNTS(POOL)=J
      ASSOCIATE(R=>ORBITS(J,POOL))
         R%PART=PART
         R%L=L
         R%ICASE=ICASE
         R%META=[LAMB,LAMH,WFUN,H4,FAC,OB,OB0,SLAMD0]
         R%W=W
         ALLOCATE(R%V(N,5))
         R%V(:,1)=V1
         R%V(:,2)=V2
         R%V(:,3)=V3
         R%V(:,4)=V4
         R%V(:,5)=V5
      END ASSOCIATE
      IF (ICASE.EQ.4) REFERENCES(L,POOL)=J
      END SUBROUTINE KESNAP_ORBIT

      REAL(DP) FUNCTION KESNAP_ACTION(V,Y) RESULT(ACTION)
      COMPLEX(DP), INTENT(IN) :: V(:,:),Y(:,:)
      COMPLEX(DP) :: AMPLITUDE
      INTEGER :: C,M
C     Assemble the same KH drive documented at KHERMFILL.  Its scalar
C     action is qualified against the unmodified native KHERMQUAD.
      AMPLITUDE=0.
      DO C=1,5
      DO M=1,SIZE(Y,1)
         AMPLITUDE=AMPLITUDE+V(M,C)*Y(M,C)
      ENDDO
      ENDDO
      ACTION=ABS(AMPLITUDE)**2
      END FUNCTION KESNAP_ACTION

      SUBROUTINE KESNAP_USE(CELL,PLACE,JS,KGRID,N,Y,ALPHAD,
     &                      RADIAL,QNATIVE)
      INTEGER, INTENT(IN) :: CELL,PLACE,JS,KGRID,N
      COMPLEX(DP), INTENT(IN) :: Y(N,5),QNATIVE(3)
      REAL(DP), INTENT(IN) :: ALPHAD,RADIAL
      CHARACTER(96) :: NAME
      CHARACTER(2048) :: LINE
      INTEGER :: POOL,J,IREF,C
      REAL(DP) :: ACTION,ACTION0
      POOL=KESNAP_POOL(JS,KGRID)
      IF (POOL.EQ.0) ERROR STOP 'ENERGY SNAPSHOT USE GRID LIMIT'
      IF (.NOT.ALLOCATED(ORBITS))
     &   ERROR STOP 'ENERGY SNAPSHOT ORBITS MISSING'
      IF (COUNTS(POOL).EQ.0) ERROR STOP 'ENERGY SNAPSHOT GRID MISSING'
      WRITE(NAME,'(A,I0,A,I0,A)')
     &   'ENERGY_SNAPSHOT_W',CELL,'_P',PLACE,'.OUT'
      DO C=3,5
         WRITE(LINE,'(A,5(I0,1X),4(ES25.16E3,1X))')
     &      'Q ',CELL,PLACE,JS,KGRID,C,ALPHAD,RADIAL,QNATIVE(C-2)
         CALL KESNAP_LINE(NAME,
     &      '# V2 Q CELL PLACE JS GRID COMPONENT ALPHAD RADIAL '//
     &      'NATIVE_Q_RE NATIVE_Q_IM; S JS GRID PART L ICASE '//
     &      'LAMB LAMH WFUN H4 FAC OB OB0 SLAMD0 W_RE W_IM '//
     &      'ACTION ACTION0 ALPHAD',LINE)
      ENDDO
      DO J=1,COUNTS(POOL)
         ASSOCIATE(R=>ORBITS(J,POOL))
            ACTION=KESNAP_ACTION(R%V,Y)
            ACTION0=0.
            IF (R%PART.EQ.0.AND.R%META(8).GT.0..AND.
     &          R%ICASE.EQ.1) THEN
               IREF=REFERENCES(R%L,POOL)
               IF (IREF.GT.0)
     &            ACTION0=KESNAP_ACTION(ORBITS(IREF,POOL)%V,Y)
            ENDIF
            WRITE(LINE,'(A,5(I0,1X),13(ES25.16E3,1X))')
     &         'S ',JS,KGRID,R%PART,R%L,R%ICASE,R%META,R%W,
     &         ACTION,ACTION0,ALPHAD
            CALL KESNAP_LINE(NAME,'',LINE)
         END ASSOCIATE
      ENDDO
      END SUBROUTINE KESNAP_USE
      END MODULE KENERGYSNAPSHOTM

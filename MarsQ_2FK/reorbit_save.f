         YRE(NREEQ+9,K) = ABS(RE_PERTURB(1))
      ENDDO
      ENDDO
      ENDDO
      ENDIF

      IF (KRE_INIT.EQ.3) THEN
C     1D UNIFORM DISTRIBUTION IN S^2
C     S-DIMENSION=NREORBIT 
C     USEFUL FOR FIELD LINE TRACING, BY SETTING RE_LAMBDA0=0 
C     AND SMALL RE_P0
      NRER = NREORBIT+1
      NRE1 = NRER-1
